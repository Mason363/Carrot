import AppKit

/// Supplies recently copied text as prediction context.
///
/// macOS (15.4+) asks the user before an app reads the clipboard programmatically. Carrot never
/// triggers that prompt in the background: it reads silently only when access is already allowed,
/// and offers an explicit "Allow" action (onboarding / Settings) that performs the first read on
/// purpose. Password managers' concealed or transient copies are always ignored, and nothing is stored.
@MainActor
final class ClipboardMonitor: ObservableObject {
    static let shared = ClipboardMonitor()

    enum Access: Equatable {
        /// Reading never prompts (older macOS, or the user chose "Always Allow").
        case allowed
        /// Reading would show the system's paste prompt.
        case wouldPrompt
        /// The user blocked clipboard access in System Settings.
        case denied
    }

    @Published private(set) var access: Access = .wouldPrompt

    private let pasteboard = NSPasteboard.general
    private var lastChangeCount: Int
    private var text: String?
    private var copiedAt: Date?
    /// How long a copy stays relevant.
    private let freshness: TimeInterval = 20 * 60
    private static let maxLength = 2000

    private init() {
        lastChangeCount = pasteboard.changeCount
        updateAccess()
    }

    func updateAccess() {
        if #available(macOS 15.4, *) {
            switch pasteboard.accessBehavior {
            case .alwaysAllow: access = .allowed
            case .alwaysDeny: access = .denied
            default: access = .wouldPrompt
            }
        } else {
            access = .allowed
        }
    }

    /// The recent copy, if any. Cheap: only reads the clipboard when its change count moved and
    /// reading is allowed without a prompt.
    func recentText() -> String? {
        guard Preferences.shared.useClipboard else { return nil }
        if pasteboard.changeCount != lastChangeCount {
            lastChangeCount = pasteboard.changeCount
            copiedAt = Date()
            text = nil
            updateAccess()
            if access == .allowed { text = readCurrent() }
        }
        guard let copiedAt, Date().timeIntervalSince(copiedAt) < freshness else { return nil }
        return text
    }

    /// User-initiated: read once so macOS can ask for permission now, in context.
    func requestAccess() {
        _ = readCurrent()
        updateAccess()
        lastChangeCount = -1 // re-evaluate on next use
    }

    private func readCurrent() -> String? {
        let types = pasteboard.types ?? []
        // nspasteboard.org markers used by password managers and clipboard tools.
        let private_ = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                        "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"]
        if types.contains(where: { private_.contains($0.rawValue) }) { return nil }
        guard types.contains(.string), var string = pasteboard.string(forType: .string) else { return nil }
        // Huge copies: cut by UTF-16 length first (cheap) before anything counts characters.
        let ns = string as NSString
        if ns.length > Self.maxLength * 4 {
            string = ns.substring(with: ns.rangeOfComposedCharacterSequences(for: NSRange(location: 0, length: Self.maxLength * 4)))
        }
        string = string.trimmingCharacters(in: .whitespacesAndNewlines)
        guard string.count >= 2 else { return nil }
        if string.count > Self.maxLength { string = String(string.prefix(Self.maxLength)) }
        // Long random-looking strings are likely secrets (tokens, keys); single-line ones only.
        if !string.contains(" "), string.count >= 24,
           string.range(of: "^[A-Za-z0-9_\\-+/=.]{24,}$", options: .regularExpression) != nil,
           !string.hasPrefix("http") {
            return nil
        }
        return MemoryStore.sanitize(string)
    }
}
